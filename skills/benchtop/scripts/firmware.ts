// Firmware scaffold: bun firmware.ts <projectDir> [--force]
//
// Writes <projectDir>/firmware/ from project.json so pin numbers cannot drift from the
// wiring: pins.h is generated from the same nets the wiring guide is drawn from, and a
// bring-up sketch proves each part is connected before the real firmware is written.
//
//   always overwritten: platformio.ini, include/pins.h, src/bringup.cpp (arduino)
//   created if missing (or with --force): src/main.cpp, <slug>.yaml (esphome)

import { mkdir } from "node:fs/promises";
import { join } from "node:path";
import { type Family, FAMILIES, isEsp32, resolveBoard } from "./lib/platform";
import { type PinEntryDetail, bringUpPlan, pinMapDetailed, stalePinNames } from "./lib/pinmap";
import { type Loaded, ProjectError, loadProject, main } from "./lib/project";

// The PlatformIO platform follows firmware.board, and every platform is pinned to an exact
// version in lib/platform.ts (FAMILIES), with the reason in a comment there.
const ESP32 = FAMILIES[0]!;

/** ESP32-C3 and ESP32-S3 boards: native USB, so Serial must be routed to USB CDC. */
const NATIVE_USB_BOARD = /esp32[-_]?(c3|s3)|(^|[-_])(c3|s3)([-_]|$)/i;

const GENERATED = "GENERATED by benchtop firmware.ts from project.json.";

type Firmware = NonNullable<Loaded["project"]["firmware"]>;

const hex = (n: number): string => `0x${n.toString(16).toUpperCase().padStart(2, "0")}`;
const cstr = (s: string): string => JSON.stringify(s);

function pad(rows: string[][]): string[] {
  const widths: number[] = [];
  for (const r of rows) r.forEach((c, i) => (widths[i] = Math.max(widths[i] ?? 0, c.length)));
  return rows.map((r) => r.map((c, i) => (i < r.length - 1 ? c.padEnd(widths[i]!) : c)).join(" ").trimEnd());
}

// ---------------------------------------------------------------------------- pins

function pinsHeader(loaded: Loaded, pins: PinEntryDetail[]): string {
  const rows = pins.map((p) => [`#define ${p.name}`, String(p.gpio), `// ${p.net}: ${p.comment}`]);
  return [
    `// ${GENERATED}`,
    "// DO NOT EDIT BY HAND: change the wiring in project.json and re-run firmware.ts.",
    "// This file is the only source of pin numbers. Never type a GPIO number elsewhere.",
    `// Project: ${loaded.project.slug}`,
    "#pragma once",
    "",
    ...pad(rows),
    "",
  ].join("\n");
}

function pinsPython(loaded: Loaded, pins: PinEntryDetail[]): string {
  const rows = pins.map((p) => [`${p.name} =`, String(p.gpio), `# ${p.net}: ${p.comment}`]);
  return [
    `# ${GENERATED}`,
    "# DO NOT EDIT BY HAND: change the wiring in project.json and re-run firmware.ts.",
    `# Project: ${loaded.project.slug}`,
    "",
    ...pad(rows),
    "",
  ].join("\n");
}

// ---------------------------------------------------------------------- platformio

export function platformioIni(fw: Firmware, family: Family = ESP32): string {
  // Native USB flags are an ESP32 thing: on an RP2040 Serial is USB already, on AVR it is the UART.
  const usb = family.id === "esp32" && NATIVE_USB_BOARD.test(fw.board);
  const lines = [
    `; ${GENERATED}`,
    "; Regenerated on every run: change libs and board in project.json, not here.",
    "",
    "[platformio]",
    "default_envs = main",
    "",
    "; Shared by both environments.",
    "[env]",
    ...family.comment,
    `platform = ${family.platform}@${family.version}`,
    `board = ${fw.board}`,
    "framework = arduino",
    "monitor_speed = 115200",
    ...family.envLines,
  ];
  for (const [k, v] of Object.entries(fw.boardOptions ?? {})) {
    // The file is an ini: a key or value with a newline could add settings nobody wrote.
    if (!/^board_[A-Za-z0-9_.]+$/.test(k) || /[\r\n]/.test(v)) {
      throw new ProjectError(`firmware.boardOptions: "${k}" is not a PlatformIO board setting. Keys start with "board_", for example "board_build.arduino.memory_type".`);
    }
    lines.push(`${k} = ${v}`);
  }
  const extra = fw.buildFlags ?? [];
  const badFlag = extra.find((f) => /[\r\n]/.test(f) || !f.trim().startsWith("-"));
  if (badFlag !== undefined) throw new ProjectError(`firmware.buildFlags: "${badFlag}" is not a compiler flag. Each entry is one flag starting with "-", for example "-DBOARD_HAS_PSRAM".`);
  if (usb || extra.length) {
    if (usb) {
      lines.push(
        "; Native USB: route Serial to USB CDC. On a board whose USB port goes through a",
        "; UART bridge chip (some S3 devkits), remove the two ARDUINO_USB lines or Serial goes silent.",
      );
    }
    lines.push("build_flags =");
    if (usb) lines.push("  -DARDUINO_USB_MODE=1", "  -DARDUINO_USB_CDC_ON_BOOT=1");
    if (extra.length) lines.push("  ; from firmware.buildFlags in project.json", ...extra.map((f) => `  ${f.trim()}`));
  }
  lines.push(
    "",
    "; The real firmware: src/main.cpp.",
    "[env:main]",
    "build_src_filter = +<*> -<bringup.cpp>",
  );
  if (fw.libs?.length) lines.push("lib_deps =", ...fw.libs.map((l) => `  ${l}`));
  lines.push(
    "",
    "; Bring-up sketch: proves wiring before the real firmware exists. Needs no libraries.",
    "[env:bringup]",
    "build_src_filter = +<*> -<main.cpp>",
    "",
  );
  return lines.join("\n");
}

// ----------------------------------------------------------------------- bring-up

/**
 * Which I2C controller an RP2040 SDA/SCL pair belongs to: GPIO n%4 is 0 (i2c0 SDA), 1 (i2c0 SCL),
 * 2 (i2c1 SDA) or 3 (i2c1 SCL). Anything else is not a valid pair on either controller.
 */
export function rp2040I2cBus(sda: number, scl: number): "Wire" | "Wire1" | null {
  if (sda % 4 === 0 && scl % 4 === 1) return "Wire";
  if (sda % 4 === 2 && scl % 4 === 3) return "Wire1";
  return null;
}

/**
 * The bring-up sketch. Per family: ESP32 and RP2040 have Serial.printf; AVR has not, and has
 * 2 KB of RAM, so its text is printed with Serial.print and kept in flash with F(). I2C pins are
 * chosen with Wire.begin(sda, scl) on ESP32, Wire.setSDA/setSCL on RP2040, and fixed on AVR.
 */
export function bringupCpp(loaded: Loaded, pins: PinEntryDetail[], family: Family = ESP32): string {
  const avr = family.id === "avr";
  const rp = family.id === "rp2040";
  /** A string literal for Serial.println: in flash on AVR, where RAM is 2 KB. */
  const lit = (s: string): string => (avr ? `F(${cstr(s)})` : cstr(s));
  const sda = pins.find((p) => p.use === "bus-sda");
  const scl = pins.find((p) => p.use === "bus-scl");
  const expected = loaded.placed
    .filter((p) => p.def.electrical.i2cAddresses?.length)
    .map((p) => ({ label: `${p.def.name} (${p.use.ref})`, addrs: p.def.electrical.i2cAddresses! }));
  const outs = pins.filter((p) => p.use === "output");
  const ins = pins.filter((p) => p.use === "input" || p.use === "analog");

  const c: string[] = [
    `// ${GENERATED}`,
    "// Bring-up sketch, built only by [env:bringup]. Regenerated on every run; do not edit.",
    "// Prints the pin map, scans I2C, checks the outputs, then reports inputs every second.",
    "// Every output is first put at its idle level. Only parts whose part file marks them safe",
    "// (an LED, a buzzer) are switched on for 400 ms. Relays, servos, motor drivers and data",
    "// lines are held at idle and named on the serial port: test those from main.cpp, load disconnected.",
    "#include <Arduino.h>",
    "#include <Wire.h>",
    '#include "pins.h"',
    "",
  ];

  if (sda && scl && expected.length) {
    c.push("struct Expect {", "  const char* part;", "  const uint8_t* addrs;", "  uint8_t count;", "};");
    expected.forEach((e, i) => c.push(`static const uint8_t ADDRS_${i}[] = {${e.addrs.map(hex).join(", ")}};`));
    c.push("static const Expect EXPECTED[] = {");
    expected.forEach((e, i) => c.push(`  {${cstr(e.label)}, ADDRS_${i}, ${e.addrs.length}},`));
    c.push("};", "");
  }

  // The controller the I2C pins sit on (RP2040 has two; ESP32 and AVR have one Wire object).
  const rpBus = sda && scl ? rp2040I2cBus(sda.gpio, scl.gpio) : null;
  const wire = rp && rpBus ? rpBus : "Wire";

  if (avr && sda && scl) {
    c.push("// Hex byte as 0xNN. AVR has no Serial.printf.", "static void hex2(uint8_t v) {", '  Serial.print(F("0x"));', "  if (v < 0x10) Serial.print('0');", "  Serial.print(v, HEX);", "}", "");
  }

  c.push("static void printPinMap() {", `  Serial.println(${lit("[pins] pin map from pins.h")});`);
  for (const p of pins) {
    if (avr) {
      c.push(`  Serial.print(F(${cstr(`  ${p.name.padEnd(18)} GPIO`)})); Serial.print(${p.name}); Serial.println(F(${cstr(` ${p.net}: ${p.comment}`)}));`);
    } else {
      c.push(`  Serial.printf("  %-18s GPIO%-3d %s\\n", ${cstr(p.name)}, ${p.name}, ${cstr(`${p.net}: ${p.comment}`)});`);
    }
  }
  c.push("}", "");

  if (sda && scl) {
    c.push(
      "static bool probe(uint8_t addr) {",
      `  ${wire}.beginTransmission(addr);`,
      `  return ${wire}.endTransmission() == 0;`,
      "}",
      "",
      "static void scanI2c() {",
    );
    if (rp) {
      if (rpBus) c.push(`  ${wire}.setSDA(${sda.name});`, `  ${wire}.setSCL(${scl.name});`, `  ${wire}.begin();`);
      else {
        // Not a valid pair on either controller: say so on the port rather than failing the build.
        c.push(
          `  // ${sda.name} (GPIO${sda.gpio}) and ${scl.name} (GPIO${scl.gpio}) are not an SDA/SCL pair on either RP2040 I2C controller.`,
          "  // i2c0 SDA is GPIO 0, 4, 8, ... with SCL one higher; i2c1 SDA is GPIO 2, 6, 10, ... with SCL one higher.",
          `  Serial.println(${lit(`[i2c] ${sda.name} GPIO${sda.gpio} and ${scl.name} GPIO${scl.gpio} are not an SDA/SCL pair on either RP2040 I2C controller: fix the wiring`)});`,
          `  ${wire}.setSDA(${sda.name});`,
          `  ${wire}.setSCL(${scl.name});`,
          `  ${wire}.begin();`,
        );
      }
    } else if (avr) {
      c.push(
        `  // AVR Wire is on fixed pins (SDA and SCL in the board's pins_arduino.h); ${sda.name} and ${scl.name} cannot move it.`,
        `  if (${sda.name} != SDA || ${scl.name} != SCL) Serial.println(F("[i2c] pins.h names SDA/SCL pins that are not this board's fixed I2C pins: the scan below uses the fixed ones"));`,
        "  Wire.begin();",
      );
    } else {
      c.push(`  Wire.begin(${sda.name}, ${scl.name});`);
    }
    c.push(
      `  Serial.println(${lit("[i2c] scanning 0x08-0x77")});`,
      "  bool seen[128] = {false};",
      "  int count = 0;",
      "  for (uint8_t a = 0x08; a <= 0x77; a++) {",
      "    if (probe(a)) {",
      "      seen[a] = true;",
      "      count++;",
      avr ? '      Serial.print(F("  device at ")); hex2(a); Serial.println();' : '      Serial.printf("  device at 0x%02X\\n", a);',
      "    }",
      "  }",
      `  if (count == 0) Serial.println(${lit("  nothing answered: check 3V3, GND, SDA/SCL and that the pins are not swapped")});`,
    );
    if (expected.length) {
      c.push(
        "  for (const Expect& e : EXPECTED) {",
        "    int hit = -1;",
        "    for (uint8_t i = 0; i < e.count; i++) {",
        "      if (seen[e.addrs[i]]) { hit = e.addrs[i]; break; }",
        "    }",
      );
      if (avr) {
        c.push(
          '    if (hit >= 0) { Serial.print(F("[ OK ] ")); Serial.print(e.part); Serial.print(F(" found at ")); hex2(hit); Serial.println(); }',
          "    else {",
          '      Serial.print(F("[MISS] ")); Serial.print(e.part); Serial.print(F(" missing, expected at"));',
          "      for (uint8_t i = 0; i < e.count; i++) { Serial.print(' '); hex2(e.addrs[i]); }",
          "      Serial.println();",
          "    }",
          "  }",
        );
      } else {
        c.push(
          '    if (hit >= 0) Serial.printf("[ OK ] %s found at 0x%02X\\n", e.part, hit);',
          "    else {",
          '      Serial.printf("[MISS] %s missing, expected at", e.part);',
          '      for (uint8_t i = 0; i < e.count; i++) Serial.printf(" 0x%02X", e.addrs[i]);',
          "      Serial.println();",
          "    }",
          "  }",
        );
      }
    }
    c.push("}", "");
  }

  c.push("void setup() {", "  Serial.begin(115200);", "  uint32_t t0 = millis();", "  while (!Serial && millis() - t0 < 3000) delay(10);", "  delay(300);");
  c.push(`  Serial.println(${lit(`\n=== bring-up: ${loaded.project.slug} ===`)});`, "  printPinMap();");
  if (sda && scl) c.push("  scanI2c();");
  else if (expected.length) c.push(`  Serial.println(${lit("[i2c] parts expect I2C addresses but no SDA/SCL net reaches the controller")});`);

  // Idle levels first, for every output, before any of them is exercised: a low-triggered
  // relay must not sit at LOW while the test works its way down the list.
  const plans = outs.map((p) => ({ p, plan: bringUpPlan(p) }));
  for (const { p, plan } of plans) {
    if ((p.controller.pin.caps ?? []).some((c2) => c2 === "flash" || c2 === "usb")) continue;
    c.push(`  digitalWrite(${p.name}, ${plan.idle});`, `  pinMode(${p.name}, OUTPUT);`);
  }
  for (const { p, plan } of plans) {
    if (!plan.pulse) {
      c.push(`  Serial.println(${lit(`[out] ${p.name} GPIO${p.gpio} held ${plan.idle}, not switched: ${plan.target}. Reason: ${plan.why}.`)});`);
      continue;
    }
    const active = plan.idle === "HIGH" ? "LOW" : "HIGH";
    c.push(
      `  Serial.println(${lit(`[out] ${p.name} GPIO${p.gpio} on for 400 ms: ${plan.target}`)});`,
      `  digitalWrite(${p.name}, ${active});`,
      "  delay(400);",
      `  digitalWrite(${p.name}, ${plan.idle});`,
      "  delay(400);",
    );
  }
  if (!outs.length) c.push(`  Serial.println(${lit("[out] no output pins in this project")});`);

  for (const p of ins) {
    if (p.use === "analog") continue;
    // Buttons wired to ground need the internal pull-up; other inputs are left floating.
    const pull = p.others.some((o) => o.part.def.kind === "input") ? "INPUT_PULLUP" : "INPUT";
    c.push(`  pinMode(${p.name}, ${pull});`);
  }
  c.push(`  Serial.println(${lit("[in] reporting inputs once a second")});`, "}", "");

  c.push("void loop() {", avr ? '  Serial.print(F("[in] t=")); Serial.print((unsigned long)(millis() / 1000)); Serial.print(\'s\');' : '  Serial.printf("[in] t=%lus", (unsigned long)(millis() / 1000));');
  for (const p of ins) {
    const read = p.use === "analog" ? `analogRead(${p.name})` : `digitalRead(${p.name})`;
    c.push(avr ? `  Serial.print(F(" ${p.name}=")); Serial.print(${read});` : `  Serial.printf(" ${p.name}=%d", ${read});`);
  }
  c.push("  Serial.println();", "  delay(1000);", "}", "");
  return c.join("\n");
}

// ----------------------------------------------------------------------- main.cpp

function mainCpp(loaded: Loaded, fw: Firmware): string {
  const behaviour = fw.behaviour.replace(/\*\//g, "* /");
  return [
    "/*",
    ` * ${loaded.project.name}: behaviour from project.json`,
    " *",
    ...behaviour.split("\n").map((l) => ` * ${l}`.trimEnd()),
    " *",
    " * Pin numbers come only from pins.h. Run the bring-up environment first:",
    " *   pio run -e bringup -t upload",
    " */",
    "#include <Arduino.h>",
    '#include "pins.h"',
    "",
    "void setup() {",
    "  Serial.begin(115200);",
    "}",
    "",
    "void loop() {",
    "}",
    "",
  ].join("\n");
}

// ----------------------------------------------------------------------- esphome

function esphomeYaml(loaded: Loaded, fw: Firmware, pins: PinEntryDetail[]): string {
  const sda = pins.find((p) => p.use === "bus-sda");
  const scl = pins.find((p) => p.use === "bus-scl");
  const name = loaded.project.slug.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
  const y = [
    `# ${GENERATED}`,
    "# Substitutions are the only source of pin numbers; reference them as ${PIN_...}.",
    "substitutions:",
    ...pins.map((p) => `  ${p.name}: GPIO${p.gpio}  # ${p.net}: ${p.comment}`),
    "",
    "esphome:",
    `  name: ${name}`,
    "",
    "esp32:",
    `  board: ${fw.board}`,
    "  framework:",
    "    type: arduino",
    "",
    "logger:",
    "",
  ];
  if (sda && scl) {
    y.push("i2c:", `  sda: \${${sda.name}}`, `  scl: \${${scl.name}}`, "  scan: true", "");
  }
  y.push("# Behaviour (from project.json):", ...fw.behaviour.split("\n").map((l) => `# ${l}`), "");
  return y.join("\n");
}

// --------------------------------------------------------------------------- cli

async function write(path: string, body: string, mode: "always" | "missing" | "force", force: boolean): Promise<string> {
  const exists = await Bun.file(path).exists();
  if (exists && mode === "missing" && !force) return `kept     ${path} (exists; --force to overwrite)`;
  await Bun.write(path, body);
  return `${exists ? "replaced" : "wrote   "} ${path}`;
}

/** esp-idf and ESPHome's esp32 block build ESP32 chips only; a Pico or an Uno needs framework "arduino". */
async function warnIfNotEsp32(fw: Firmware, what: string): Promise<void> {
  const t = await resolveBoard(fw.board);
  if (t.ok && !isEsp32(t.family)) {
    console.log(`warning: ${what} only builds ESP32 chips, but board "${fw.board}" is ${t.family.label}. Set firmware.framework to "arduino" (this scaffold then builds and compiles it for ${t.family.label}), or keep ${what} and expect no scaffold beyond the pin file.`);
  }
}

async function run(): Promise<void> {
  const args = process.argv.slice(2);
  const force = args.includes("--force");
  const dir = args.find((a) => !a.startsWith("--"));
  if (!dir) throw new ProjectError("usage: bun firmware.ts <projectDir> [--force]");

  const loaded = await loadProject(dir);
  const fw = loaded.project.firmware;
  if (!fw) throw new ProjectError(`${loaded.dir}/project.json has no "firmware" section (framework, board, behaviour)`);
  const pins = pinMapDetailed(loaded);
  if (!pins.length) console.error("warning: no net reaches a controller pin with a gpio number; the pin map is empty");

  const out = join(loaded.dir, "firmware");
  await mkdir(join(out, "include"), { recursive: true });
  const log: string[] = [];

  switch (fw.framework) {
    case "arduino": {
      const target = await resolveBoard(fw.board);
      if (!target.ok) {
        // No platform for this board: the pin file is still worth having, the rest would not build.
        log.push(await write(join(out, "include", "pins.h"), pinsHeader(loaded, pins), "always", force));
        console.log(log.join("\n"));
        console.log(`warning: firmware scaffold limited to include/pins.h: ${target.reason}`);
        break;
      }
      const family = target.family;
      console.log(`platform: ${family.platform}@${family.version} for board ${fw.board} (${family.label}, from ${target.how === "PlatformIO" ? "PlatformIO's board list" : "the board name"})`);
      await mkdir(join(out, "src"), { recursive: true });
      log.push(await write(join(out, "platformio.ini"), platformioIni(fw, family), "always", force));
      log.push(await write(join(out, "include", "pins.h"), pinsHeader(loaded, pins), "always", force));
      log.push(await write(join(out, "src", "bringup.cpp"), bringupCpp(loaded, pins, family), "always", force));
      log.push(await write(join(out, "src", "main.cpp"), mainCpp(loaded, fw), "missing", force));
      console.log(log.join("\n"));
      // main.cpp is kept across runs while pins.h is rewritten, so a net renamed in
      // project.json leaves main.cpp using a constant that no longer exists.
      const stale = stalePinNames(await Bun.file(join(out, "src", "main.cpp")).text(), pins.map((p) => p.name));
      if (stale.length) {
        console.log(
          `warning: src/main.cpp uses ${stale.join(", ")}, which pins.h does not define. A pin constant is named after its net, so a renamed or removed net renames or removes it. pins.h now has: ${pins.map((p) => p.name).join(", ") || "nothing"}. Update main.cpp; it will not compile as it is.`,
        );
      }
      console.log(
        [
          "",
          "Flash the bring-up sketch first and read the serial output:",
          `  pio run -d "${out}" -e bringup -t upload && pio device monitor -d "${out}"`,
          "Then the main firmware:",
          `  pio run -d "${out}" -e main -t upload`,
        ].join("\n"),
      );
      break;
    }
    case "esphome": {
      await warnIfNotEsp32(fw, "ESPHome (as written here, an esp32: block)");
      log.push(await write(join(out, `${loaded.project.slug}.yaml`), esphomeYaml(loaded, fw, pins), "missing", force));
      console.log(log.join("\n"));
      console.log(`\nCompile and flash:\n  esphome run "${join(out, `${loaded.project.slug}.yaml`)}"`);
      break;
    }
    case "esp-idf": {
      await warnIfNotEsp32(fw, "ESP-IDF");
      log.push(await write(join(out, "include", "pins.h"), pinsHeader(loaded, pins), "always", force));
      console.log(log.join("\n"));
      console.log("\nesp-idf: only pins.h is generated. CMake, sdkconfig and main are up to the agent.");
      break;
    }
    case "micropython": {
      log.push(await write(join(out, "pins.py"), pinsPython(loaded, pins), "always", force));
      console.log(log.join("\n"));
      console.log("\nmicropython: only pins.py is generated. boot.py, main.py and flashing are up to the agent.");
      break;
    }
    default: {
      const other: never = fw.framework;
      throw new ProjectError(`unknown firmware.framework "${String(other)}"`);
    }
  }
}

if (import.meta.main) await main(run);
